//! 经验统计（**2026-09 重写**）。
//!
//! 只做一件事：从游戏画面里读 `EXP 427096(46.09%)` 那一行，算每分钟/每小时收益
//! 和升级还需多久。整条链路只截屏读像素，**不碰游戏进程内存**。
//!
//! # 分层
//!
//! | 模块 | 负责 |
//! | --- | --- |
//! | [`capture`] | 找到游戏窗口，用**后台截屏**抓客户区最底下那一条 |
//! | [`font`] | 内置的 14 个字形（`0-9 ( ) . %`）、切字、**纯结构**定位字段 |
//! | [`table`] | 120 级经验表、累计经验账本、`advance`（升级永不为负） |
//! | [`reader`] | 抓屏 → 认字 → 经验表自检，交出一个 [`reader::Sample`] |
//! | [`tracker`] | 会话状态机、每分钟/每小时速率、升级预计、历史落库 |
//!
//! # 这一版修掉的三件事（都有实测依据，不是猜的）
//!
//! ## 1. 抓屏方式（这是「经常识别不到」的头号原因）
//!
//! 旧实现从**屏幕 DC** 抓「屏幕上那个矩形」，游戏上面压着任何窗口
//! （浏览器、聊天窗、别的工具）抓回来的就是那个窗口的像素，于是报
//! 「画面上没有经验那一行」，用户读成「不在角色里 / 去校准一次」，方向全错。
//!
//! 实测：同一个探针，游戏被浏览器挡住时，屏幕 DC 抓到的墨点占比是 **100%**
//! （浏览器的白底），而 `PrintWindow` 抓到的还是游戏自己（**20.2%**，和前台时逐点相同）。
//! 现在改成后台截屏，**合成在哪一层都不影响**。
//!
//! ## 2. 字形表必须完整（「不要临时去学习」）
//!
//! 经验那一行的字符集是封闭的 14 个符号，那就没有任何理由在运行时去学。
//! 旧实现只内置了一部分、缺的靠自动学习补，结果时好时坏：真机上 50 帧里
//! 只有 8 帧读得出来 —— 因为 20 级的经验值里含数字 `1` 的比例很高，而 `1` 正是缺的那个。
//! 现在 14 个全部内置（`builtin_font_is_complete` 钉着），开箱即用。
//!
//! ## 3. 字段定位不能看字形间隙
//!
//! 数字 `1` 的字形只有 2 像素宽，而它占的字格是 5 像素 —— 右边会空出 3 像素。
//! 旧实现用「空隙 ≤ 2 算贴在一起」来切出字段，这个 3 像素的空隙就把字段从中间切断，
//! 整帧作废；更糟的是有些帧会被悄悄**截掉开头那位**（`2302` 其实真值是 `12302`）。
//! 现在按**纯结构**解析（从 `)` 往左严格按 `数字(整数.两位小数%)` 吃字形），
//! 空隙多大都无所谓，而且任何一位对不上就整帧作废，绝不给出半个数字。

